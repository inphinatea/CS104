def scoreToLetter(grade):
  # Converts the Grade Number into a Letter
  if grade >= 90:
    return("A")
  elif grade >= 80:
    return("B")
  elif grade >= 70:
    return("C")
  elif grade >= 60:
    return("D")
  else:
    return("F")

# General Variables
names = []
grades = []
sum = 0
while True:
  try:
    number = int(input("Enter Number of Students: "))
    break;
  except ValueError:
    print("Invalid Input")
    exit()


for i in range(number):
  # Takes Inputs for Names and Grades
  names.append(input("Enter Name Here: "))
  grades.append(input("Enter Grade Here: "))

with open("grade_report.txt", "w") as f:
  for i in range(number):
    # Finds the Spacing for the Name
    space = (10 - len(names[i])) * " "
    space1 = (5 - len(grades[i])) * " "
    letter = scoreToLetter(float(grades[i]))
    # Writes the Name and Grade to the File
    f.write(f"{names[i]}: {space} {grades[i]} {space1} {letter}\n")
    sum += float(grades[i])

  # Writes the Average Grade to the File
  f.write(f"Average Grade: {float(sum / number):.2f}")
  average = float(sum / number)
  letterAverage = scoreToLetter(average)
  f.write(f"\nAverage Letter Grade: {letterAverage}")

print("File grade_report.txt is made")